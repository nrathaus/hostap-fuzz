#!/usr/bin/env python3
"""Generate N station configurations that differ in one negotiated setting.

A one-peer run cannot produce concurrent-session stimulus at all: whatever a
single station negotiates is the only thing the AP has live at any moment. Two
stations that negotiated the SAME thing are barely better -- they exercise one
subsystem twice. What is worth producing is N peers whose sessions are in
different subsystems at the same time, so that whatever state those subsystems
share is under both at once.

The setting they differ in is the finite cyclic group, because it is the one
negotiated property whose domain this tree already derives: the registry is
read out of dragonfly.c and crypto.c by fuzzing/axes/families.py, 20 members
the tree can instantiate, 7 past the production filter. Nothing here is a list
someone typed, which is the whole reason it is read rather than written.

    python3 peers.py [CHECKOUT] N DIR     write N station configs into DIR
    python3 peers.py [CHECKOUT] N         print the assignment and stop
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "axes"))

import families                                            # noqa: E402

TEMPLATE = """# Station %(i)d of %(n)d, generated by fuzzing/topology/peers.py.
# Everything here is identical to its siblings except the group, so whatever
# the run finds attributes to that one line.
ctrl_interface=%(rundir)s/ctrl
update_config=0
ap_scan=1

# Where the AP is. Scanning the band between cases is most of a run's wall
# clock and none of its coverage.
freq_list=2437
scan_res_valid_for_connect=3600

# The one line that differs. Group %(group)s of the %(ngroups)d this tree can
# instantiate. The AP is configured to accept every group its stations chose,
# so which one a session ends up in is this station's decision and the AP
# ends up running %(n)d sessions in different group code at once.
sae_groups=%(group)s

network={
\tssid="%(ssid)s"
\tkey_mgmt=SAE
\tsae_password="%(password)s"
\tieee80211w=2
}
"""


def groups(root, production_only=False):
    """The groups to spread peers across, nearest to usable first.

    Three tiers, in this order:

      1. no build gate AND past dragonfly_suitable_group() -- these complete
         in a stock build, so a station assigned one actually associates
      2. no build gate, but the production filter rejects them -- reachable
         only with CONFIG_TESTING_OPTIONS, where sae_set_group() skips it
      3. gated at build time (ALL_DH_GROUPS, the brainpool NIDs)

    The order matters because a group the build cannot instantiate gives a
    station that never associates: a peer contributing nothing, rather than a
    peer contributing a refusal. Two peers is the common case and the first
    two entries have to be two that work.

    The tiers themselves are read out of the tree, not decided here --
    fuzzing/axes/families.py gets them from dragonfly.c and crypto.c.
    """
    reg = families.group_registry(root)
    prod = set(reg["production"])
    ungated, gated = [], []
    for tier in ("ecc", "ffc"):
        for value, gate in reg[tier]:
            (gated if gate else ungated).append(value)
    usable = [v for v in ungated if v in prod]
    if production_only:
        return usable
    return usable + [v for v in ungated if v not in prod] + gated


def assign(root, n, production_only=False):
    """Which group each of the n peers uses."""
    g = groups(root, production_only)
    if not g:
        return []
    return [g[i % len(g)] for i in range(n)]


def generate(root, n, outdir, ssid, password, rundir, production_only=False):
    picked = assign(root, n, production_only)
    total = len(groups(root, production_only))
    out = []
    for i, group in enumerate(picked):
        # wpa_supplicant creates the control socket but not the directory
        # holding it, and refuses to start without one -- which with several
        # stations reads as "another wpa_supplicant is already running".
        os.makedirs(os.path.join(rundir, "sta%d" % i), exist_ok=True)
        path = os.path.join(outdir, "sta%d.conf" % i)
        with open(path, "w", encoding="utf-8") as f:
            f.write(TEMPLATE % {
                "i": i, "n": n, "group": group, "ngroups": total,
                "rundir": os.path.join(rundir, "sta%d" % i),
                "ssid": ssid, "password": password,
            })
        out.append((path, group))
    return out


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    root = os.path.abspath(args[0]) if args and os.path.isdir(args[0]) \
        else os.getcwd()
    rest = args[1:] if args and os.path.isdir(args[0]) else args
    n = int(rest[0]) if rest else 2
    prod = "--production" in sys.argv

    if "--groups" in sys.argv:
        # The distinct groups N peers will use, for the AP config: it has to
        # accept every one of them, or which group a session lands in stops
        # being the station's choice and becomes a second variable.
        print(" ".join(str(g) for g in sorted(set(assign(root, n, prod)))))
        return 0

    if len(rest) < 2:
        g = groups(root, prod)
        print("%d group(s) available: %s" % (len(g), g))
        for i, group in enumerate(assign(root, n, prod)):
            print("  station %d -> sae_groups=%s" % (i, group))
        return 0

    outdir = rest[1]
    made = generate(root, n, outdir,
                    os.environ.get("FUZZ_SSID", "hostap-fuzz-net"),
                    os.environ.get("FUZZ_PASSWORD", "fuzzfuzzfuzz"),
                    os.environ.get("FUZZ_RUNDIR", outdir), prod)
    for path, group in made:
        print("%s group=%s" % (path, group))
    return 0


if __name__ == "__main__":
    sys.exit(main())
